#!/usr/bin/env python3
"""A tiny throttled, range-capable file server for recording docs/demo.tape.

    demo_server.py PORT_FILE NAME=SIZE [NAME=SIZE ...]

Serves deterministic generated bytes (nothing on disk) at /NAME, where SIZE takes a
K/M/G suffix. Honours `Range: bytes=a-b` (206 + Content-Range), sends Accept-Ranges
and an ETag, and caps each connection at about 4 MiB/s so downloads last long enough
to pause and resume. Binds 127.0.0.1 on a free port and writes the port number to
PORT_FILE; exits non-zero if it cannot bind.
"""
import re
import sys
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

RATE = 4 * 1024 * 1024  # bytes per second per connection
BLOCK = 64 * 1024
PATTERN = bytes((i * 31 + (i >> 8)) & 0xFF for i in range(BLOCK))
FILES = {}


def parse_size(text):
    m = re.fullmatch(r"(\d+)([KMG]?)", text.upper())
    if not m:
        raise ValueError(f"bad size {text!r}")
    return int(m.group(1)) * {"": 1, "K": 1 << 10, "M": 1 << 20, "G": 1 << 30}[m.group(2)]


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *args):
        pass

    def do_HEAD(self):
        self.serve(head=True)

    def do_GET(self):
        self.serve(head=False)

    def serve(self, head):
        name = self.path.split("?", 1)[0].lstrip("/")
        size = FILES.get(name)
        if size is None:
            self.send_error(404)
            return
        start, end, status = 0, size - 1, 200
        m = re.fullmatch(r"bytes=(\d*)-(\d*)", self.headers.get("Range", ""))
        if m and (m.group(1) or m.group(2)):
            if m.group(1):
                start = int(m.group(1))
                end = min(int(m.group(2)), size - 1) if m.group(2) else size - 1
            else:
                start = max(size - int(m.group(2)), 0)
            if start >= size or start > end:
                self.send_response(416)
                self.send_header("Content-Range", f"bytes */{size}")
                self.send_header("Content-Length", "0")
                self.end_headers()
                return
            status = 206
        self.send_response(status)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("ETag", f'"{name}-{size}"')
        self.send_header("Content-Type", "application/octet-stream")
        self.send_header("Content-Length", str(end - start + 1))
        if status == 206:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.end_headers()
        if head:
            return
        pos = start
        try:
            while pos <= end:
                off = pos % BLOCK
                chunk = PATTERN[off : off + min(BLOCK - off, end - pos + 1)]
                self.wfile.write(chunk)
                pos += len(chunk)
                time.sleep(len(chunk) / RATE)
        except (BrokenPipeError, ConnectionResetError):
            pass


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    port_file = sys.argv[1]
    for spec in sys.argv[2:]:
        name, _, size = spec.partition("=")
        FILES[name] = parse_size(size)
    ThreadingHTTPServer.daemon_threads = True
    try:
        server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    except OSError as e:
        sys.exit(f"demo_server: cannot bind: {e}")
    with open(port_file, "w") as f:
        f.write(str(server.server_address[1]))
    server.serve_forever()


if __name__ == "__main__":
    main()
